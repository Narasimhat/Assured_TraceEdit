"""Generate release identity without requiring static assets in serverless runtime."""
import hashlib
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
files = [root/'app.py', root/'engine.py', root/'knockout_prediction.py', root/'reference_api.py', root/'public/unified.html', root/'public/workspace-version.js']
files += [root/'public'/name for name in ['app.js','index.html','standalone-coding.js','design-workflow.js','style.css','standalone-clean.css']]
files += [root/'visual_report.py', root/'publication_report.py', root/'public/standalone-publication.js']
files += sorted((root/'public/unified').rglob('*.js'))
files += sorted((root/'public/unified').rglob('*.css'))
digest = hashlib.sha256(b''.join(p.relative_to(root).as_posix().encode()+b'\0'+p.read_bytes().replace(b'\r\n', b'\n') for p in files)).hexdigest()[:12]
version = re.search(r"VERSION = '([^']+)'", (root/'public/unified/core.js').read_text(encoding='utf-8')).group(1)
(root/'workspace_build.py').write_text(f'# Generated by scripts/build_workspace_version.py before release.\nWORKSPACE_VERSION = {version!r}\nWORKSPACE_BUILD = {digest!r}\n', encoding='utf-8')
print(digest)
